"""Writes a starter gate.toml for a repo it has never seen.

It only records what it can observe: the commands the repo already defines and
the import directions it already respects. Limits are left at their defaults (exemptions are only suggested),
and accepting the baseline stays a separate, deliberate step.
"""

from __future__ import annotations

import json
import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from . import propose
from .checks import size, toolchain
from .config import STRUCTURAL
from .context import Context
from .findings import FAIL


@dataclass
class Plan:
    toolchain: dict[str, str] = field(default_factory=dict)
    tests: dict[str, str] = field(default_factory=dict)
    commands: dict[str, str] = field(default_factory=dict)
    boundaries: list[str] = field(default_factory=list)
    declarative: list[tuple[str, int]] = field(default_factory=list)  # (path, proposed line limit)
    fast: list[str] = field(default_factory=lambda: list(STRUCTURAL))
    full: list[str] = field(default_factory=list)


def plan(ctx: Context) -> Plan:
    p = Plan()
    _node(ctx.root, p)
    _python(ctx.root, p)
    _other_stacks(ctx.root, p)
    p.boundaries = propose.boundary_rules(ctx.root, ctx.repo_files)
    p.declarative = _declarative(ctx)
    # A check with no tool behind it would be skipped locally and fail under
    # --strict in CI, so it only joins a profile when something can run it.
    if "lint" in p.toolchain or toolchain.available(ctx, "lint"):
        p.fast.append("lint")
    p.full = list(p.fast)
    if "typecheck" in p.toolchain or toolchain.available(ctx, "typecheck"):
        p.full.append("typecheck")
    p.full += list(p.tests)
    return p


_DECLARATIVE = re.compile(r"(^|[/._-])(schemas?|seeds?|migrations?|fixtures?)([/._-]|$)", re.IGNORECASE)


def _declarative(ctx: Context) -> list[tuple[str, int]]:
    """Over-limit files whose name says they hold data or definitions, with a limit that leaves room to grow."""
    out = []
    for finding in size.run(ctx):
        if finding.severity == FAIL and _DECLARATIVE.search(finding.path) and finding.value:
            out.append((finding.path, (int(finding.value) // 500 + 1) * 500))
    return out


def _node(root: Path, p: Plan) -> None:
    try:
        scripts = json.loads((root / "package.json").read_text(encoding="utf-8")).get("scripts", {})
    except (OSError, ValueError):
        return
    run = _node_runner(root)
    for script, category in (("lint", "lint"), ("typecheck", "typecheck"), ("format:check", "format")):
        if script in scripts:
            p.toolchain[category] = run(script)
    if "test" in scripts:
        p.tests["unit"] = run("test")
    if "test:integration" in scripts:
        p.tests["integration"] = run("test:integration")
    for script in ("test:e2e", "e2e"):
        if script in scripts:
            p.commands["e2e"] = run(script)
            break


def _node_runner(root: Path):
    for lockfile, manager in (("pnpm-lock.yaml", "pnpm"), ("yarn.lock", "yarn"), ("bun.lockb", "bun")):
        if (root / lockfile).exists():
            return lambda script: f"{manager} run {script}"
    return lambda script: f"npm run {script} --silent"


def _python(root: Path, p: Plan) -> None:
    configured = (root / "pytest.ini").exists() or (root / "conftest.py").exists()
    try:
        tool = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8")).get("tool", {})
        configured = configured or "pytest" in tool
    except (OSError, ValueError):
        pass
    has_tests = any((root / d).is_dir() and any((root / d).rglob("test_*.py")) for d in ("tests", "test"))
    if (configured or has_tests) and "unit" not in p.tests:
        p.tests["unit"] = "python -m pytest -q"


def _other_stacks(root: Path, p: Plan) -> None:
    for marker, command in (("Cargo.toml", "cargo test -q"), ("go.mod", "go test ./..."), ("Package.swift", "swift test")):
        if (root / marker).exists() and "unit" not in p.tests:
            p.tests["unit"] = command


def render(p: Plan) -> str:
    q = json.dumps  # a JSON string is a valid TOML basic string
    out = [
        "# Rules this repo is held to. Checked by `gate check`.",
        "# Generated by `gate init` from what the repo already does. Review it, then either fix",
        "# what `gate check` reports or record it with `gate baseline --accept`.",
        "",
        "# Limits are the defaults; uncomment to change them.",
        "# [complexity]",
        "# ccn_warn = 10",
        "# ccn_fail = 15",
        "# max_function_lines = 80",
        "# max_parameters = 5",
        "#",
        "# [size]",
        "# max_file_lines_warn = 300",
        "# max_file_lines_fail = 500",
        "# max_test_file_lines_fail = 1000",
        "#",
        "# Suppression markers (lint and type ignores, skipped tests, coverage exclusions) are findings.",
        "# To stop counting a kind, list only the ones you want:",
        "# [suppressions]",
        '# kinds = ["lint", "type", "test", "coverage"]',
        "#",
        "# A limit can be changed for some files. A long UI component that is mostly markup:",
        "# [[complexity.override]]",
        '# glob = "**/*.tsx"',
        "# max_function_lines = 150",
    ]
    if p.declarative:
        out += ["",
                "# These files are over the size limit and look declarative (a schema, seed data, migrations,",
                "# fixtures). If splitting one would be artificial, uncomment its exemption rather than",
                "# baselining it. If it mixes in logic, leave it to fail.",
                *(line for path, limit in p.declarative for line in
                  ("# [[size.override]]", f"# glob = {q(path)}", f"# max_file_lines_fail = {limit}"))]
    if p.boundaries:
        out += ["", "[boundaries]",
                "# Proposed from today's imports: every rule below already holds.",
                "# Delete the ones that are coincidence rather than intent.",
                "forbid = [", *(f"  {q(rule)}," for rule in p.boundaries), "]"]
    if p.toolchain:
        out += ["", "[toolchain]", *(f"{category} = {q(cmd)}" for category, cmd in p.toolchain.items())]
    for name, cmd in p.tests.items():
        out += ["", f"[tests.{name}]", f"command = {q(cmd)}"]
    for name, cmd in p.commands.items():
        out += ["", "# Not in a profile: add its name to one once it can run unattended.",
                "[[command]]", f"name = {q(name)}", f"run = {q(cmd)}"]
    out += ["", "[profiles]",
            "# fast runs when an agent stops; full is for CI and before merging.",
            f"fast = {q(p.fast)}", f"full = {q(p.full)}", ""]
    return "\n".join(out)
