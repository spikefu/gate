"""Renders gate.toml as prose for the instruction files agents read.

Why: an agent told one set of rules and checked against another will keep
failing the gate without knowing why. Generating the prose from the config
means the two cannot drift, and `--check` lets CI prove it.

Only the block between the markers is gate's. Everything else in the file
belongs to its author and is left untouched.
"""

from __future__ import annotations

from pathlib import Path

from .config import Config

START = "<!-- gate:rules:start -->"
END = "<!-- gate:rules:end -->"
DEFAULT_TARGETS = ("AGENTS.md", "CLAUDE.md")


def targets(root: Path, config: Config) -> list[Path]:
    """Configured files, else whichever instruction files exist, else AGENTS.md."""
    if config.rules_targets:
        return [root / t for t in config.rules_targets]
    existing = [root / t for t in DEFAULT_TARGETS if (root / t).is_file()]
    return existing or [root / DEFAULT_TARGETS[0]]


def render(config: Config) -> str:
    lines = [
        START,
        "## Rules this repo is held to",
        "",
        "Generated by `gate rules` from `gate.toml`. Do not edit this section; change `gate.toml` and rerun.",
        "",
        "Run `gate check --changed` before you finish. It must pass.",
        "",
        "### Limits",
        "",
        *_limits(config),
        *_boundaries(config),
        "",
        "### Checks",
        "",
        *_checks(config),
        "",
        "### Existing violations",
        "",
        "- Violations that predate these rules are recorded in `.gate/baseline.json`. Do not make them worse.",
        "- Never run `gate baseline --accept`, edit the baseline by hand, or change a limit to make a finding go away.",
        "- Never delete, skip, or loosen a test to get a check to pass.",
        "",
        *_IMPROVING,
        END,
    ]
    return "\n".join(lines) + "\n"


# Without this, the rules above read as a fence to stay inside. They are also a
# draft to be improved, and the agent working in the code sees its gaps first.
_IMPROVING = [
    "### Improving these rules",
    "",
    "These rules are a draft, and you are expected to challenge them. Passing the gate is the minimum; "
    "noticing where it falls short is part of the work. As you go, look for:",
    "",
    "- a problem that got through because no rule or check covers it",
    "- a limit that is looser than the code needs, or stricter than is useful",
    "- a boundary the code keeps to that is not written down",
    "- a finding that is wrong: say so instead of working around it",
    "- a check that was skipped, or that no profile runs",
    "",
    "Run `gate gaps` for the weaknesses gate can see for itself, then add what only a reader of the code can see.",
    "",
    "Say what you found in your report, even when nobody asked, with the evidence and the exact change you propose: "
    "the `gate.toml` edit, or a script to add as a `[[command]]` check when gate has no check for it. "
    "Propose; do not apply. What the rules are is the human's decision.",
]


def _limits(config: Config) -> list[str]:
    c, s = config.complexity, config.size
    out = [
        f"- Functions: cyclomatic complexity at most {c.ccn_fail} (warns above {c.ccn_warn}), "
        f"at most {c.max_function_lines} lines, at most {c.max_parameters} parameters.",
        f"- Files: at most {s.fail} lines (warns above {s.warn}).",
    ]
    if s.test_fail != s.fail:
        out.append(f"- Test files: at most {s.test_fail} lines.")
    for o in s.overrides:
        if o.fail is not None:
            out.append(f"- Files matching `{o.glob}`: at most {o.fail} lines.")
    for glob, limits in c.overrides:
        names = {"ccn_warn": "complexity warns above", "ccn_fail": "complexity at most",
                 "max_function_lines": "function lines at most", "max_parameters": "parameters at most"}
        out.append(f"- Functions in files matching `{glob}`: {', '.join(f'{names[k]} {v}' for k, v in limits)}.")
    return out


def _boundaries(config: Config) -> list[str]:
    b = config.boundaries
    if not b.forbid and not b.only:
        return []
    out = ["", "### Boundaries", ""]
    out += [f"- `{left}` must not import `{right}`." for left, right in b.forbid]
    for rule in b.only:
        allowed = ", ".join(f"`{a}`" for a in rule.allowed_from)
        scope = f" (applies to code under {', '.join(f'`{s}`' for s in rule.applies_to)})" if rule.applies_to else ""
        why = f" {rule.why.rstrip('.')}." if rule.why else ""
        out.append(f"- Only {allowed} may import `{rule.target}`{scope}.{why}")
    return out


def _checks(config: Config) -> list[str]:
    out = []
    for name in sorted(config.profiles):
        marker = " (default)" if name == config.default_profile else ""
        out.append(f"- `gate check --profile {name}`{marker}: {', '.join(config.profiles[name])}.")
    commands = {**config.toolchain, **{n: c.run for n, c in config.tests.items()},
                **{n: c.run for n, c in config.commands.items()}}
    out += [f"- `{name}` runs `{run}`." for name, run in commands.items()]
    return out


def apply(existing: str, block: str) -> str:
    """Put `block` into a file's text: replace gate's section if present, else append it."""
    start, end = existing.find(START), existing.find(END)
    if start != -1 and end > start:
        return existing[:start] + block.rstrip("\n") + existing[end + len(END):]
    if not existing.strip():
        return block
    return existing.rstrip("\n") + "\n\n" + block


def stale(root: Path, config: Config) -> list[Path]:
    """Targets whose rules section is missing or out of date."""
    block = render(config)
    out = []
    for path in targets(root, config):
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if apply(current, block) != current:
            out.append(path)
    return out


def write(root: Path, config: Config) -> list[Path]:
    """Bring every stale target up to date. Returns the files it changed."""
    block = render(config)
    changed = stale(root, config)
    for path in changed:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        path.write_text(apply(current, block), encoding="utf-8")
    return changed
